-- =============================================================================
-- OLTP  : Sistem Manajemen Kost (versi latihan Workshop Data Warehouse)
-- Target: PostgreSQL 15+  (juga kompatibel dengan Supabase)
-- Isi   : 6 tipe enumerasi, 7 tabel, batasan integritas, indeks, trigger updated_at
--
-- Catatan desain (lihat docs/TEORI_WDW.md):
--  * 3NF  : status okupansi kamar TIDAK disimpan di rooms; diturunkan dari contracts.
--  * Soft-state: baris tidak dihapus untuk transaksi (invoice 'cancelled', kontrak
--    'terminated'), sehingga CDC berbasis updated_at tetap akurat.
--  * Semua tabel memiliki created_at + updated_at (timestamptz) sebagai dasar
--    incremental extraction pada ETL.
-- =============================================================================

SET timezone = 'Asia/Jakarta';

CREATE EXTENSION IF NOT EXISTS btree_gist;   -- untuk EXCLUDE (tanpa tumpang tindih)

-- ---------------------------------------------------------------------------
-- 1. Tipe enumerasi (domain nilai tertutup)
-- ---------------------------------------------------------------------------
CREATE TYPE user_role          AS ENUM ('owner', 'tenant');
CREATE TYPE contract_status    AS ENUM ('active', 'completed', 'terminated');
CREATE TYPE invoice_status     AS ENUM ('unpaid', 'paid', 'overdue', 'cancelled');
CREATE TYPE payment_method     AS ENUM ('tunai', 'transfer_bank', 'dompet_digital');
CREATE TYPE complaint_status   AS ENUM ('open', 'in_progress', 'resolved');
CREATE TYPE complaint_category AS ENUM ('listrik', 'air', 'furnitur', 'kebersihan', 'keamanan', 'lainnya');

-- ---------------------------------------------------------------------------
-- 2. Fungsi pembantu: pembaruan otomatis updated_at
--    Jika pemanggil sengaja mengisi updated_at (mis. data simulasi), nilainya
--    dihormati; jika tidak, diisi now().
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
    NEW.updated_at := now();
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------------
-- 3. Tabel master
-- ---------------------------------------------------------------------------
CREATE TABLE users (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role           user_role    NOT NULL,
  full_name      varchar(150) NOT NULL,
  email          varchar(150) NOT NULL,
  phone          varchar(20)  NOT NULL,
  password_hash  text         NOT NULL,          -- di Supabase: diganti auth.users
  business_name  varchar(150),                   -- hanya relevan untuk owner
  created_at     timestamptz  NOT NULL DEFAULT now(),
  updated_at     timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT users_phone_uq UNIQUE (phone)
);
CREATE UNIQUE INDEX users_email_uq ON users (lower(email));

CREATE TABLE properties (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id       bigint       NOT NULL REFERENCES users(id),
  name           varchar(150) NOT NULL,
  property_type  varchar(20)  NOT NULL DEFAULT 'campur',
  address        text         NOT NULL,
  city           varchar(100) NOT NULL,
  created_at     timestamptz  NOT NULL DEFAULT now(),
  updated_at     timestamptz  NOT NULL DEFAULT now(),
  CONSTRAINT properties_type_ck CHECK (property_type IN ('putra', 'putri', 'campur')),
  CONSTRAINT properties_owner_name_uq UNIQUE (owner_id, name)
);

CREATE TABLE rooms (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id     bigint        NOT NULL REFERENCES properties(id),
  room_number     varchar(20)   NOT NULL,
  room_type       varchar(50)   NOT NULL DEFAULT 'Standar',
  price           numeric(14,2) NOT NULL,        -- tarif sewa per bulan (daftar harga)
  deposit_amount  numeric(14,2) NOT NULL DEFAULT 0,
  created_at      timestamptz   NOT NULL DEFAULT now(),
  updated_at      timestamptz   NOT NULL DEFAULT now(),
  CONSTRAINT rooms_price_ck   CHECK (price > 0),
  CONSTRAINT rooms_deposit_ck CHECK (deposit_amount >= 0),
  CONSTRAINT rooms_number_uq  UNIQUE (property_id, room_number)
);

-- ---------------------------------------------------------------------------
-- 4. Tabel transaksi
-- ---------------------------------------------------------------------------
CREATE TABLE contracts (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint          NOT NULL REFERENCES users(id),
  room_id         bigint          NOT NULL REFERENCES rooms(id),
  start_date      date            NOT NULL,      -- selalu tanggal 1
  end_date        date            NOT NULL,
  rent_amount     numeric(14,2)   NOT NULL,      -- nilai sewa yang DISEPAKATI
  deposit_amount  numeric(14,2)   NOT NULL DEFAULT 0,
  due_day         smallint        NOT NULL DEFAULT 5,
  status          contract_status NOT NULL DEFAULT 'active',
  created_at      timestamptz     NOT NULL DEFAULT now(),
  updated_at      timestamptz     NOT NULL DEFAULT now(),
  CONSTRAINT contracts_dates_ck   CHECK (end_date >= start_date),
  CONSTRAINT contracts_start_ck   CHECK (EXTRACT(DAY FROM start_date) = 1),
  CONSTRAINT contracts_rent_ck    CHECK (rent_amount > 0),
  CONSTRAINT contracts_deposit_ck CHECK (deposit_amount >= 0),
  CONSTRAINT contracts_dueday_ck  CHECK (due_day BETWEEN 1 AND 28),
  -- AB-05: satu kamar tidak boleh memiliki dua kontrak yang tumpang tindih
  CONSTRAINT contracts_no_overlap EXCLUDE USING gist (
    room_id WITH =, daterange(start_date, end_date, '[]') WITH &&
  )
);
-- AB-06: satu penyewa hanya boleh memiliki satu kontrak berstatus active
CREATE UNIQUE INDEX contracts_one_active_per_tenant ON contracts (tenant_id) WHERE status = 'active';
CREATE INDEX contracts_room_idx   ON contracts (room_id);
CREATE INDEX contracts_tenant_idx ON contracts (tenant_id);

CREATE TABLE invoices (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id   bigint         NOT NULL REFERENCES contracts(id),
  period_month  date           NOT NULL,         -- tanggal 1 pada bulan tagihan
  due_date      date           NOT NULL,
  amount        numeric(14,2)  NOT NULL,         -- nilai yang DITAGIHKAN
  status        invoice_status NOT NULL DEFAULT 'unpaid',
  created_at    timestamptz    NOT NULL DEFAULT now(),
  updated_at    timestamptz    NOT NULL DEFAULT now(),
  CONSTRAINT invoices_period_ck CHECK (EXTRACT(DAY FROM period_month) = 1),
  CONSTRAINT invoices_amount_ck CHECK (amount > 0),
  -- AB-07: satu tagihan per kontrak per bulan
  CONSTRAINT invoices_contract_period_uq UNIQUE (contract_id, period_month)
);
CREATE INDEX invoices_status_due_idx ON invoices (status, due_date);

CREATE TABLE payments (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id   bigint         NOT NULL REFERENCES invoices(id),
  amount       numeric(14,2)  NOT NULL,          -- nilai yang DITERIMA
  method       payment_method NOT NULL,
  paid_at      timestamptz    NOT NULL,
  recorded_by  bigint         NOT NULL REFERENCES users(id),   -- owner yang mencatat
  note         text,
  created_at   timestamptz    NOT NULL DEFAULT now(),
  updated_at   timestamptz    NOT NULL DEFAULT now(),
  CONSTRAINT payments_amount_ck CHECK (amount > 0),
  -- Penyederhanaan: satu tagihan dilunasi dengan tepat satu pembayaran
  CONSTRAINT payments_invoice_uq UNIQUE (invoice_id)
);

-- ---------------------------------------------------------------------------
-- 5. Operasional: pengaduan (ditangani langsung oleh owner)
-- ---------------------------------------------------------------------------
CREATE TABLE complaints (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        bigint             NOT NULL REFERENCES users(id),
  room_id          bigint             NOT NULL REFERENCES rooms(id),
  category         complaint_category NOT NULL,
  description      text               NOT NULL,
  status           complaint_status   NOT NULL DEFAULT 'open',
  created_at       timestamptz        NOT NULL DEFAULT now(),   -- diajukan
  handled_at       timestamptz,                                  -- mulai ditangani
  resolved_at      timestamptz,                                  -- selesai
  resolution_note  text,
  updated_at       timestamptz        NOT NULL DEFAULT now(),
  CONSTRAINT complaints_handled_ck  CHECK (handled_at  IS NULL OR handled_at  >= created_at),
  CONSTRAINT complaints_resolved_ck CHECK (resolved_at IS NULL OR resolved_at >= COALESCE(handled_at, created_at)),
  CONSTRAINT complaints_status_ck   CHECK ((status = 'resolved') = (resolved_at IS NOT NULL))
);
CREATE INDEX complaints_room_idx   ON complaints (room_id);
CREATE INDEX complaints_tenant_idx ON complaints (tenant_id);

-- ---------------------------------------------------------------------------
-- 6. Dasar CDC: indeks updated_at + trigger pada semua tabel
-- ---------------------------------------------------------------------------
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['users','properties','rooms','contracts','invoices','payments','complaints']
  LOOP
    EXECUTE format('CREATE INDEX %I ON %I (updated_at)', t || '_updated_at_idx', t);
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
                   'trg_' || t || '_updated_at', t);
  END LOOP;
END $$;
