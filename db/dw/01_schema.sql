-- =============================================================================
-- DATA WAREHOUSE : Manajemen Kost (Kimball, fact constellation)
-- 3 tabel fakta + 6 dimensi, schema: dw  | staging: stg | metadata ETL: etl
--
--  Fakta                  Jenis                 Grain
--  fact_pembayaran        transaksional         1 baris per pembayaran (= per tagihan lunas)
--  fact_okupansi_harian   potret periodik       1 baris per kamar per hari
--  fact_pengaduan         potret terakumulasi   1 baris per pengaduan (di-update bertahap)
--
--  Dimensi: dim_waktu (tipe 0), dim_properti / dim_penyewa / dim_metode_pembayaran /
--           dim_kategori_pengaduan (tipe 1), dim_kamar (tipe 2 pada tarif_sewa)
-- =============================================================================

SET timezone = 'Asia/Jakarta';
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE SCHEMA IF NOT EXISTS dw;
CREATE SCHEMA IF NOT EXISTS stg;
CREATE SCHEMA IF NOT EXISTS etl;

-- ---------------------------------------------------------------------------
-- Metadata ETL: log eksekusi + watermark CDC
-- ---------------------------------------------------------------------------
CREATE TABLE etl.run_log (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at    timestamptz NOT NULL DEFAULT now(),
  finished_at   timestamptz,
  mode          varchar(12) NOT NULL,            -- full | incremental
  as_of         date        NOT NULL,
  status        varchar(10) NOT NULL DEFAULT 'running',   -- running | success | failed
  rows_extracted jsonb,
  rows_loaded    jsonb,
  step_seconds   jsonb,
  validation     jsonb,
  error          text
);

CREATE TABLE etl.watermark (
  table_name       varchar(50) PRIMARY KEY,
  last_updated_at  timestamptz NOT NULL,
  last_batch_id    bigint      NOT NULL,
  updated_at       timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- STAGING: cermin 7 tabel OLTP (kolom sensitif seperti password_hash TIDAK diambil).
-- Kolom enumerasi disimpan sebagai text. _batch_id = batch ETL terakhir yang
-- menyentuh baris tersebut -> dasar pemrosesan incremental di tahap transform.
-- ---------------------------------------------------------------------------
CREATE TABLE stg.users (
  id bigint PRIMARY KEY, role text, full_name text, email text, phone text,
  business_name text, created_at timestamptz, updated_at timestamptz, _batch_id bigint NOT NULL
);
CREATE TABLE stg.properties (
  id bigint PRIMARY KEY, owner_id bigint, name text, property_type text, address text, city text,
  created_at timestamptz, updated_at timestamptz, _batch_id bigint NOT NULL
);
CREATE TABLE stg.rooms (
  id bigint PRIMARY KEY, property_id bigint, room_number text, room_type text,
  price numeric(14,2), deposit_amount numeric(14,2),
  created_at timestamptz, updated_at timestamptz, _batch_id bigint NOT NULL
);
CREATE TABLE stg.contracts (
  id bigint PRIMARY KEY, tenant_id bigint, room_id bigint, start_date date, end_date date,
  rent_amount numeric(14,2), deposit_amount numeric(14,2), due_day smallint, status text,
  created_at timestamptz, updated_at timestamptz, _batch_id bigint NOT NULL
);
CREATE TABLE stg.invoices (
  id bigint PRIMARY KEY, contract_id bigint, period_month date, due_date date,
  amount numeric(14,2), status text,
  created_at timestamptz, updated_at timestamptz, _batch_id bigint NOT NULL
);
CREATE TABLE stg.payments (
  id bigint PRIMARY KEY, invoice_id bigint, amount numeric(14,2), method text,
  paid_at timestamptz, recorded_by bigint,
  created_at timestamptz, updated_at timestamptz, _batch_id bigint NOT NULL
);
CREATE TABLE stg.complaints (
  id bigint PRIMARY KEY, tenant_id bigint, room_id bigint, category text, status text,
  created_at timestamptz, handled_at timestamptz, resolved_at timestamptz,
  updated_at timestamptz, _batch_id bigint NOT NULL
);
CREATE INDEX ON stg.contracts (room_id);
CREATE INDEX ON stg.invoices  (contract_id);
CREATE INDEX ON stg.payments  (invoice_id);

-- ---------------------------------------------------------------------------
-- DIMENSI
-- ---------------------------------------------------------------------------
-- Fungsi band tarif: atribut turunan pada dim_kamar
CREATE OR REPLACE FUNCTION dw.fn_kelas_tarif(p_tarif numeric) RETURNS varchar AS $$
  SELECT CASE WHEN p_tarif < 1500000 THEN 'Ekonomi'
              WHEN p_tarif < 2500000 THEN 'Standar'
              ELSE 'Premium' END::varchar;
$$ LANGUAGE sql IMMUTABLE;

-- Dim_Waktu (tipe 0 / statis). Kunci cerdas yyyymmdd; 99991231 = "belum terjadi".
CREATE TABLE dw.dim_waktu (
  waktu_key          int PRIMARY KEY,
  tanggal            date        NOT NULL UNIQUE,
  hari               smallint    NOT NULL,
  hari_dalam_minggu  smallint    NOT NULL,      -- 1 = Senin ... 7 = Minggu (ISO)
  nama_hari          varchar(10) NOT NULL,
  minggu_ke          smallint    NOT NULL,
  bulan              smallint    NOT NULL,
  nama_bulan         varchar(12) NOT NULL,
  kuartal            smallint    NOT NULL,
  tahun              smallint    NOT NULL,
  periode_bulan      varchar(7)  NOT NULL,      -- YYYY-MM
  jumlah_hari_bulan  smallint    NOT NULL,
  hari_kerja         boolean     NOT NULL
);

-- Dim_Properti (tipe 1). Atribut pemilik didenormalisasi (flattening).
CREATE TABLE dw.dim_properti (
  properti_key    bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  properti_id     bigint       NOT NULL UNIQUE,      -- kunci alami (properties.id)
  nama_properti   varchar(150) NOT NULL,
  jenis_properti  varchar(20),
  kota            varchar(100) NOT NULL,
  pemilik_id      bigint       NOT NULL,
  nama_pemilik    varchar(150) NOT NULL,
  nama_usaha      varchar(150),
  etl_batch_id    bigint       NOT NULL,
  diperbarui_pada timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ON dw.dim_properti (pemilik_id);

-- Dim_Penyewa (tipe 1). Baris kunci 0 = "Kamar kosong" (unknown member).
CREATE TABLE dw.dim_penyewa (
  penyewa_key      bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  penyewa_id       bigint       NOT NULL UNIQUE,     -- kunci alami (users.id); 0 = kosong
  nama_lengkap     varchar(150) NOT NULL,
  email            varchar(150),
  telepon          varchar(20),
  tanggal_bergabung date,
  etl_batch_id     bigint       NOT NULL,
  diperbarui_pada  timestamptz  NOT NULL DEFAULT now()
);

-- Dim_Kamar (tipe 2 pada tarif_sewa). Interval versi TERTUTUP [valid_dari, valid_sampai].
CREATE TABLE dw.dim_kamar (
  kamar_key       bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  kamar_id        bigint        NOT NULL,            -- kunci alami (rooms.id)
  properti_id     bigint        NOT NULL,
  nomor_kamar     varchar(20)   NOT NULL,
  tipe_kamar      varchar(50),
  tarif_sewa      numeric(14,2) NOT NULL,            -- atribut yang dipantau SCD2
  kelas_tarif     varchar(20)   NOT NULL,            -- Ekonomi | Standar | Premium (turunan)
  nilai_deposit   numeric(14,2) NOT NULL DEFAULT 0,
  valid_dari      date          NOT NULL,
  valid_sampai    date          NOT NULL DEFAULT DATE '9999-12-31',
  baris_aktif     boolean       NOT NULL DEFAULT TRUE,
  etl_batch_id    bigint        NOT NULL,
  diperbarui_pada timestamptz   NOT NULL DEFAULT now(),
  CONSTRAINT dim_kamar_interval_ck CHECK (valid_sampai >= valid_dari),
  -- tidak boleh ada dua versi yang tumpang tindih untuk kamar yang sama
  CONSTRAINT dim_kamar_no_overlap EXCLUDE USING gist (
    kamar_id WITH =, daterange(valid_dari, valid_sampai, '[]') WITH &&
  )
);
CREATE UNIQUE INDEX dim_kamar_satu_aktif ON dw.dim_kamar (kamar_id) WHERE baris_aktif;
CREATE INDEX dim_kamar_lookup_idx ON dw.dim_kamar (kamar_id, valid_dari, valid_sampai);

-- Dim_Metode_Pembayaran (tipe 1). Baris kunci 0 = "Tidak diketahui".
CREATE TABLE dw.dim_metode_pembayaran (
  metode_key       int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  kode_metode      varchar(30) NOT NULL UNIQUE,
  nama_metode      varchar(50) NOT NULL,
  kategori_metode  varchar(20) NOT NULL              -- Tunai | Non-Tunai
);

-- Dim_Kategori_Pengaduan (tipe 1)
CREATE TABLE dw.dim_kategori_pengaduan (
  kategori_key   int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  kode_kategori  varchar(30) NOT NULL UNIQUE,
  nama_kategori  varchar(50) NOT NULL,
  kelompok       varchar(30) NOT NULL,               -- Utilitas | Fasilitas | Lingkungan | Lainnya
  sla_hari       smallint    NOT NULL                -- target lama penyelesaian (hari)
);

-- Dimensi berperan ganda (role-playing): satu Dim_Waktu, beberapa peran pada fakta
CREATE VIEW dw.dim_waktu_bayar        AS SELECT * FROM dw.dim_waktu;
CREATE VIEW dw.dim_waktu_jatuh_tempo  AS SELECT * FROM dw.dim_waktu;
CREATE VIEW dw.dim_waktu_diajukan     AS SELECT * FROM dw.dim_waktu;
CREATE VIEW dw.dim_waktu_ditangani    AS SELECT * FROM dw.dim_waktu;
CREATE VIEW dw.dim_waktu_selesai      AS SELECT * FROM dw.dim_waktu;

-- ---------------------------------------------------------------------------
-- FAKTA
-- ---------------------------------------------------------------------------
-- 1) Transaksional. Grain: satu pembayaran (satu tagihan lunas).
CREATE TABLE dw.fact_pembayaran (
  pembayaran_key         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  waktu_bayar_key        int    NOT NULL REFERENCES dw.dim_waktu,
  waktu_jatuh_tempo_key  int    NOT NULL REFERENCES dw.dim_waktu,
  penyewa_key            bigint NOT NULL REFERENCES dw.dim_penyewa,
  properti_key           bigint NOT NULL REFERENCES dw.dim_properti,
  kamar_key              bigint NOT NULL REFERENCES dw.dim_kamar,
  metode_key             int    NOT NULL REFERENCES dw.dim_metode_pembayaran,
  -- dimensi merosot (degenerate): nomor dokumen sumber
  nomor_pembayaran       varchar(20) NOT NULL UNIQUE,   -- kunci alami -> ETL idempoten
  nomor_invoice          varchar(20) NOT NULL,
  nomor_kontrak          varchar(20) NOT NULL,
  periode_tagihan        varchar(7)  NOT NULL,
  -- ukuran
  nilai_tagihan          numeric(14,2) NOT NULL,        -- aditif
  nilai_dibayar          numeric(14,2) NOT NULL,        -- aditif
  selisih_pembayaran     numeric(14,2) NOT NULL,        -- aditif (dibayar - tagihan)
  hari_keterlambatan     int           NOT NULL DEFAULT 0,   -- non-aditif (dirata-rata)
  flag_terlambat         smallint      NOT NULL DEFAULT 0,   -- aditif
  jumlah_transaksi       smallint      NOT NULL DEFAULT 1,
  etl_batch_id           bigint        NOT NULL
);
CREATE INDEX ON dw.fact_pembayaran (waktu_bayar_key);
CREATE INDEX ON dw.fact_pembayaran (properti_key);
CREATE INDEX ON dw.fact_pembayaran (kamar_key);
CREATE INDEX ON dw.fact_pembayaran (metode_key);
CREATE INDEX ON dw.fact_pembayaran (penyewa_key);

-- 2) Potret periodik. Grain: satu kamar pada satu hari.
CREATE TABLE dw.fact_okupansi_harian (
  okupansi_key          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  waktu_key             int    NOT NULL REFERENCES dw.dim_waktu,
  properti_key          bigint NOT NULL REFERENCES dw.dim_properti,
  kamar_key             bigint NOT NULL REFERENCES dw.dim_kamar,   -- versi yang berlaku pada hari itu
  penyewa_key           bigint NOT NULL REFERENCES dw.dim_penyewa, -- 0 bila kamar kosong
  jumlah_kamar          smallint NOT NULL DEFAULT 1,
  flag_terisi           smallint NOT NULL,
  flag_kosong           smallint NOT NULL,
  tarif_harian          numeric(14,2) NOT NULL,        -- tarif daftar / jumlah hari bulan
  potensi_pendapatan    numeric(14,2) NOT NULL,        -- = tarif_harian (jika kamar penuh)
  realisasi_pendapatan  numeric(14,2) NOT NULL,        -- sewa kontrak / hari bila terisi
  pendapatan_hilang     numeric(14,2) NOT NULL,        -- = potensi bila kosong, else 0
  etl_batch_id          bigint NOT NULL,
  CONSTRAINT fact_okupansi_grain_uq UNIQUE (waktu_key, kamar_key)   -- penjaga grain
);
CREATE INDEX ON dw.fact_okupansi_harian (properti_key, waktu_key);
CREATE INDEX ON dw.fact_okupansi_harian (kamar_key);

-- 3) Potret terakumulasi. Grain: satu pengaduan; baris di-update saat status berubah.
CREATE TABLE dw.fact_pengaduan (
  pengaduan_key          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  waktu_diajukan_key     int    NOT NULL REFERENCES dw.dim_waktu,
  waktu_ditangani_key    int    NOT NULL REFERENCES dw.dim_waktu,   -- 99991231 bila belum
  waktu_selesai_key      int    NOT NULL REFERENCES dw.dim_waktu,   -- 99991231 bila belum
  properti_key           bigint NOT NULL REFERENCES dw.dim_properti,
  kamar_key              bigint NOT NULL REFERENCES dw.dim_kamar,
  penyewa_key            bigint NOT NULL REFERENCES dw.dim_penyewa,
  kategori_key           int    NOT NULL REFERENCES dw.dim_kategori_pengaduan,
  nomor_pengaduan        varchar(20) NOT NULL UNIQUE,                -- dimensi merosot + kunci alami
  lag_respons_hari       int,            -- diajukan -> ditangani   (NULL sampai ditangani)
  lag_penyelesaian_hari  int,            -- ditangani -> selesai    (NULL sampai selesai)
  total_durasi_hari      int,            -- diajukan -> selesai     (NULL sampai selesai)
  umur_hari              int NOT NULL,   -- diajukan -> selesai / tanggal as-of
  flag_selesai           smallint NOT NULL DEFAULT 0,
  flag_dalam_sla         smallint NOT NULL DEFAULT 0,
  jumlah_pengaduan       smallint NOT NULL DEFAULT 1,
  etl_batch_id           bigint   NOT NULL
);
CREATE INDEX ON dw.fact_pengaduan (waktu_diajukan_key);
CREATE INDEX ON dw.fact_pengaduan (properti_key);
CREATE INDEX ON dw.fact_pengaduan (kategori_key);
